using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace CodeStraight.Core.Actions;

/// <summary>
/// Removes ordinary comments (<c>//</c> and <c>/* */</c>). Documentation comments (<c>///</c> and <c>/** */</c>), which
/// feed IntelliSense and tools like Swagger, are kept, and so are comments that tell a tool what to do
/// (<c>// ReSharper disable …</c>, <c>// language=regex</c>).
/// <para>
/// A comment alone on its line takes the whole line with it; when that leaves two blank lines together, or a blank line
/// right after <c>{</c> or right before <c>}</c>, the extra blank line goes too. A comment after code takes the spaces
/// before it; a comment before code takes the spaces after it.
/// </para>
/// </summary>
public static class CommentRemover
{
	private static readonly string[] ToolDirectives = { "ReSharper ", "language=", "lang=", "<auto-generated" };

	public static SourceText Remove(SyntaxTree tree)
	{
		SourceText text = tree.GetText();
		SyntaxNode root = tree.GetRoot();
		var removedLines = new SortedSet<int>();
		var spans = new List<TextSpan>();

		foreach (SyntaxTrivia trivia in root.DescendantTrivia(descendIntoTrivia: true))
		{
			if (!IsRemovable(trivia))
			{
				continue;
			}

			TextSpan span = trivia.Span;
			TextLine first = text.Lines.GetLineFromPosition(span.Start);
			TextLine last = text.Lines.GetLineFromPosition(span.End);
			bool codeBefore = !IsWhiteSpace(text, first.Start, span.Start);
			bool codeAfter = !IsWhiteSpace(text, span.End, last.End);

			if (!codeBefore && !codeAfter)
			{
				for (int number = first.LineNumber; number <= last.LineNumber; number++)
				{
					removedLines.Add(number);
				}
			}
			else if (!codeAfter)
			{
				int start = span.Start;
				while (start > first.Start && IsSpace(text[start - 1]))
				{
					start--;
				}

				spans.Add(TextSpan.FromBounds(start, span.End));
			}
			else
			{
				int end = span.End;
				while (end < last.End && IsSpace(text[end]))
				{
					end++;
				}

				// "a /* x */, b" → "a, b": before punctuation the spaces in front of the comment go too.
				int start = span.Start;
				if (text[end] is ',' or ';' or ')' or ']')
				{
					while (start > first.Start && IsSpace(text[start - 1]))
					{
						start--;
					}
				}

				spans.Add(TextSpan.FromBounds(start, end));
			}
		}

		if (removedLines.Count == 0 && spans.Count == 0)
		{
			return text;
		}

		foreach (int number in RedundantBlankLines(text, removedLines))
		{
			removedLines.Add(number);
		}

		spans.AddRange(removedLines.Select(number => text.Lines[number].SpanIncludingLineBreak));
		return text.WithChanges(Merge(spans).Select(span => new TextChange(span, string.Empty)));
	}

	private static bool IsRemovable(SyntaxTrivia trivia)
	{
		// Documentation comments are other kinds of trivia (SingleLine/MultiLineDocumentationCommentTrivia).
		if (!trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) && !trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
		{
			return false;
		}

		// Both "//" and "/*" are two characters long.
		string content = trivia.ToString().Substring(2).TrimStart();
		return !ToolDirectives.Any(directive => content.StartsWith(directive, StringComparison.OrdinalIgnoreCase));
	}

	/// <summary>
	/// For every run of removed lines, the blank line that would be left over: one of two blank lines that end up
	/// together, a blank line right after <c>{</c> (or the start of the file), or one right before <c>}</c>.
	/// </summary>
	private static IEnumerable<int> RedundantBlankLines(SourceText text, SortedSet<int> removedLines)
	{
		var result = new List<int>();
		foreach (int number in removedLines)
		{
			if (removedLines.Contains(number - 1))
			{
				continue;
			}

			int after = number;
			while (removedLines.Contains(after + 1))
			{
				after++;
			}

			int previous = number - 1;
			int next = after + 1;
			bool previousOpens = previous < 0 || LineText(text, previous).EndsWith("{", StringComparison.Ordinal);
			bool previousBlank = previous >= 0 && LineText(text, previous).Length == 0;
			bool nextBlank = next < text.Lines.Count && LineText(text, next).Length == 0;
			bool nextCloses = next >= text.Lines.Count || LineText(text, next).StartsWith("}", StringComparison.Ordinal);

			if ((previousOpens || previousBlank) && nextBlank)
			{
				result.Add(next);
			}
			else if (previousBlank && nextCloses)
			{
				result.Add(previous);
			}
		}

		return result;
	}

	private static string LineText(SourceText text, int number) => text.ToString(text.Lines[number].Span).Trim();

	/// <summary>Two comments on the same line can claim the same spaces; overlapping spans are joined.</summary>
	private static IEnumerable<TextSpan> Merge(IEnumerable<TextSpan> spans)
	{
		TextSpan? current = null;
		foreach (TextSpan span in spans.OrderBy(span => span.Start))
		{
			if (current is TextSpan open && span.Start <= open.End)
			{
				current = TextSpan.FromBounds(open.Start, Math.Max(open.End, span.End));
				continue;
			}

			if (current is TextSpan done)
			{
				yield return done;
			}

			current = span;
		}

		if (current is TextSpan last)
		{
			yield return last;
		}
	}

	private static bool IsWhiteSpace(SourceText text, int start, int end)
	{
		for (int position = start; position < end; position++)
		{
			if (!char.IsWhiteSpace(text[position]))
			{
				return false;
			}
		}

		return true;
	}

	private static bool IsSpace(char c) => c is ' ' or '\t';
}
