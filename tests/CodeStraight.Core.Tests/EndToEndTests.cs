using Xunit;

namespace CodeStraight.Core.Tests;

public sealed class EndToEndTests
{
	private const string AllFeatures = """
		format_on_save = true
		rename_symbols = true
		namespace_declarations = true
		remove_unused_usings = true
		sort_usings = true
		accessibility_modifiers = true
		format_document = true
		wrap_long_lines = true
		trailing_comma = true
		trailing_comma_style = omit
		""";

	private static readonly string EditorConfig = Samples.NamingRules + """

		indent_style = tab
		tab_width = 4
		max_line_length = 80
		csharp_style_namespace_declarations = file_scoped:warning
		dotnet_style_require_accessibility_modifiers = for_non_interface_members:warning
		""";

	[Fact]
	public async Task EveryEnabledActionIsAppliedInASingleRun()
	{
		const string source = """
			using System.Text;
			using System;

			namespace Demo.Servicios
			{
			    public class Persona
			    {
			        public string Nombre { get; set; } = "";
			        public int Edad { get; set; }
			    }

			    public class Servicio
			    {
			        private int contador;

			        public Persona Crear(string nombreCompletoDeLaPersona, int edadDeLaPersona, DateTime fecha)
			        {
			            contador++;
			            return new Persona
			            {
			                Nombre = nombreCompletoDeLaPersona,
			                Edad = edadDeLaPersona,
			            };
			        }
			    }
			}
			""";

		string result = await TestWorkspace.ApplyAsync(source, AllFeatures, EditorConfig);

		Assert.Equal("""
			using System;

			namespace Demo.Servicios;

			public class Persona
			{
				public string Nombre { get; set; } = "";
				public int Edad { get; set; }
			}

			public class Servicio
			{
				private int _contador;

				public Persona Crear(
					string nombreCompletoDeLaPersona,
					int edadDeLaPersona,
					DateTime fecha)
				{
					_contador++;
					return new Persona
					{
						Nombre = nombreCompletoDeLaPersona,
						Edad = edadDeLaPersona
					};
				}
			}

			""", result);
	}

	[Fact]
	public async Task GeneratedFiles_AreLeftUntouched()
	{
		const string source = "// <auto-generated />\nusing System.Text;\nnamespace A\n{\n    class C { int x; }\n}\n";

		string result = await TestWorkspace.ApplyAsync(source, AllFeatures, EditorConfig);

		Assert.Equal(source, result);
	}
}
